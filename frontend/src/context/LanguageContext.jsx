export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem("erp_language") || "es");

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  function changeLanguage(nextLanguage) {
    setLanguage(nextLanguage);
    localStorage.setItem("erp_language", nextLanguage);
    document.documentElement.lang = nextLanguage;
  }

  function toggleLanguage() {
    changeLanguage(language === "en" ? "es" : "en");
  }

  function t(text) {
    return translateMessage(text, language);
  }

  const value = useMemo(() => ({ language, setLanguage: changeLanguage, toggleLanguage, t }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
